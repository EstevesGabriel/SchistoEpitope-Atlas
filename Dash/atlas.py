@callback(
    Output("epitope-table-container", "children"),
    Input("epitope-host", "value"),
    Input("epitope-protein", "value"),
)
def update_epitope_table(host, protein):
    if not host or not protein:
        return html.Div("Selecione um grupo e uma proteína.", className="empty-state")
    config = HOST_CONFIG[host]
    dataframe = DATASETS[host]
    peptide_col = config["peptide"]
    subset = dataframe.loc[dataframe["Proteins"].eq(protein)].copy()
    subset = subset.loc[:, [peptide_col] + config["samples"]]
    return dash_table.DataTable(
        data=subset.to_dict("records"),
        columns=[{"name": col, "id": col} for col in subset.columns],
        filter_action="native",
        sort_action="native",
        page_size=12,
        fixed_rows={"headers": True},
        style_table={"overflowX": "auto", "maxHeight": "560px", "overflowY": "auto"},
        style_header={"backgroundColor": "#F8FAFC", "fontWeight": "600", "border": "1px solid #D6DEE8"},
        style_cell={"padding": "10px", "fontFamily": "Inter, sans-serif", "border": "1px solid #E9ECEF", "textAlign": "left", "minWidth": "110px"},
    )


