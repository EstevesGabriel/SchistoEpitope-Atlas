def host_proteins(host: str) -> list[str]:
    """Return unique protein labels in source order."""
    return DATASETS[host]["Proteins"].dropna().drop_duplicates().tolist()


def counts(host: str) -> dict[str, int]:
    """Compute summary counts for an organism."""
    dataframe = DATASETS[host]
    peptide_col = HOST_CONFIG[host]["peptide"]
    return {
        "samples": len(HOST_CONFIG[host]["samples"]),
        "proteins": int(dataframe["Proteins"].nunique()),
        "epitopes": int(dataframe[peptide_col].notna().sum()),
    }


def percentile_transform(matrix: pd.DataFrame) -> pd.DataFrame:
    """Map all valid matrix values to their empirical percentile (0–100)."""
    values = matrix.to_numpy(dtype=float)
    valid_mask = ~np.isnan(values)
    output = values.copy()

    if not valid_mask.any():
        return pd.DataFrame(output, index=matrix.index, columns=matrix.columns)

    valid = pd.Series(values[valid_mask])
    output[valid_mask] = valid.rank(method="average", pct=True).to_numpy() * 100
    return pd.DataFrame(output, index=matrix.index, columns=matrix.columns)


def zscore_transform(matrix: pd.DataFrame) -> pd.DataFrame:
    """Apply a global z-score across all valid cells in the matrix."""
    values = matrix.to_numpy(dtype=float)
    valid_mask = ~np.isnan(values)
    output = values.copy()

    if not valid_mask.any():
        return pd.DataFrame(output, index=matrix.index, columns=matrix.columns)

    valid = values[valid_mask]
    mean = float(valid.mean())
    std = float(valid.std())

    if std == 0:
        output[valid_mask] = 0.0
    else:
        output[valid_mask] = (valid - mean) / std

    return pd.DataFrame(output, index=matrix.index, columns=matrix.columns)

def build_heatmap(host: str, protein: str, selected_samples: list[str], scale_mode: str, palette: str, vmax: float):
    """Build a configurable Plotly heatmap and preserve original values in hover."""
    config = HOST_CONFIG[host]
    dataframe = DATASETS[host]

    subset = dataframe.loc[dataframe["Proteins"].eq(protein)].copy()
    peptide_col = config["peptide"]
    subset = subset.dropna(subset=[peptide_col])

    matrix = subset.loc[:, [peptide_col] + selected_samples].set_index(peptide_col)
    matrix = matrix.apply(pd.to_numeric, errors="coerce")
    original = matrix.copy()

    if scale_mode == "linear":
        display_matrix = matrix
        colorbar_title = "Reatividade"
        zmin, zmax = 0, float(vmax)
        colorscale = PALETTES[palette]
    elif scale_mode == "log10":
        display_matrix = np.log10(matrix + 1)
        colorbar_title = "log10(Reatividade + 1)"
        zmin, zmax = float(display_matrix.min().min(skipna=True)), float(display_matrix.max().max(skipna=True))
        colorscale = PALETTES[palette]
    elif scale_mode == "percentile":
        display_matrix = percentile_transform(matrix)
        colorbar_title = "Percentil"
        zmin, zmax = 0, 100
        colorscale = PALETTES[palette]
    elif scale_mode == "zscore":
        display_matrix = zscore_transform(matrix)
        colorbar_title = "Z-score"
        max_abs = float(np.nanmax(np.abs(display_matrix.to_numpy()))) if not display_matrix.empty else 1
        zmin, zmax = -max_abs, max_abs
        colorscale = "RdBu_r"
    else:
        raise ValueError(f"Modo de escala não reconhecido: {scale_mode}")

    figure = px.imshow(
        display_matrix,
        zmin=zmin,
        zmax=zmax,
        color_continuous_scale=colorscale,
        aspect="auto",
        labels={"x": "Amostra", "y": "Epítopo", "color": colorbar_title},
        title=f"{config['short']} — {protein}",
    )

    original_values = original.to_numpy(dtype=float)
    figure.update_traces(
        customdata=original_values[..., None],
        hovertemplate=(
            "<b>Epítopo:</b> %{y}<br>"
            "<b>Amostra:</b> %{x}<br>"
            "<b>Valor original:</b> %{customdata[0]:,.2f}"
            "<extra></extra>"
        ),
    )

    figure.update_layout(
        template="plotly_white",
        paper_bgcolor="white",
        plot_bgcolor="white",
        margin=dict(l=160, r=40, t=70, b=110),
        coloraxis_colorbar=dict(title=colorbar_title),
        font=dict(family="Inter, Arial, sans-serif", color="#374151"),
        xaxis=dict(showgrid=False, tickangle=-90),
        yaxis=dict(showgrid=False, automargin=True),
    )

    return figure


