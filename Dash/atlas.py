def load_host(host: str) -> pd.DataFrame:
    """Load one processed host table."""
    path = HOST_CONFIG[host]["file"]
    if not path.exists():
        raise FileNotFoundError(
            f"Arquivo processado não encontrado: {path}. "
            "Execute pre_process.py antes de iniciar o Dash."
        )
    return pd.read_csv(path)


